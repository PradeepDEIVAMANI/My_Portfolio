const attributeTranslations = {
  "Jane Smith": "Camille Martin",
  "jane@company.com": "camille@entreprise.fr",
};

function translateText(text, language) {
  if (language !== "fr") return text;
  const leading = text.match(/^\s*/)?.[0] || "";
  const trailing = text.match(/\s*$/)?.[0] || "";
  const key = text.trim();
  if (translations[key]) return `${leading}${translations[key]}${trailing}`;

  // Handle wrapped in parentheses, e.g. "(Heterogeneous Apps)"
  if (key.startsWith("(") && key.endsWith(")")) {
    const inner = key.slice(1, -1).trim();
    if (translations[inner]) {
      return `${leading}(${translations[inner]})${trailing}`;
    }
  }

  // Handle bullet prefix, e.g. "· India"
  if (key.startsWith("· ")) {
    const inner = key.slice(2).trim();
    if (translations[inner]) {
      return `${leading}· ${translations[inner]}${trailing}`;
    }
  }

  return text;
}

function translateTree(node, language) {
  if (typeof node === "string") return translateText(node, language);
  if (typeof node === "number" || node == null || typeof node === "boolean") return node;
  if (Array.isArray(node)) return node.map((child) => translateTree(child, language));
  if (!React.isValidElement(node)) return node;
  const children = translateTree(node.props.children, language);
  const props = { children };
  ["placeholder", "aria-label", "title"].forEach((attribute) => {
    const value = node.props[attribute];
    if (typeof value === "string") {
      props[attribute] = language === "fr" ? (translations[value] || attributeTranslations[value] || value) : value;
    }
  });
  return React.cloneElement(node, props);
}

export function withTranslations(Component) {
  function TranslatedComponent(props) {
    const { language } = React.useContext(LanguageContext);
    return translateTree(Component(props), language);
  }
  TranslatedComponent.displayName = `withTranslations(${Component.displayName || Component.name || "Component"})`;
  return TranslatedComponent;
}
